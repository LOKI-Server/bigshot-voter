//! URLs for package assets streamed directly by LOKI.

pub fn css_href() -> &'static str {
    "/static/style.css"
}
pub fn js_href() -> &'static str {
    "/static/app.js"
}
pub fn font_href() -> &'static str {
    "/static/fonts/kavoon-latin.woff2"
}
pub fn font_ext_href() -> &'static str {
    "/static/fonts/kavoon-latin-ext.woff2"
}
